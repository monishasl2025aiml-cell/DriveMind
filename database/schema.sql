
-- DriveMind Database Schema
-- Tables: vehicles, locations, trips, trip_events
-- This file documents the existing database schema.
-- Do not run against the live database without reviewing first.

CREATE TABLE IF NOT EXISTS public.vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) UNIQUE NOT NULL,
    model VARCHAR(100) NOT NULL,
    battery INTEGER NOT NULL DEFAULT 100
        CHECK (battery BETWEEN 0 AND 100),
    status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE'
);

CREATE TABLE IF NOT EXISTS public.locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(10) UNIQUE NOT NULL,
    name VARCHAR(100) NOT NULL,
    x_coordinate DOUBLE PRECISION,
    y_coordinate DOUBLE PRECISION,
    location_type VARCHAR(30) NOT NULL DEFAULT 'JUNCTION'
);

CREATE TABLE IF NOT EXISTS public.trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    vehicle_id BIGINT NOT NULL
        REFERENCES public.vehicles(id),

    source_id BIGINT NOT NULL
        REFERENCES public.locations(id),

    destination_id BIGINT NOT NULL
        REFERENCES public.locations(id),

    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    distance DOUBLE PRECISION NOT NULL DEFAULT 0,

    battery_used INTEGER NOT NULL DEFAULT 0
        CHECK (battery_used BETWEEN 0 AND 100),

    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at TIMESTAMP,

    CHECK (source_id <> destination_id)
);

CREATE TABLE IF NOT EXISTS public.trip_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    trip_id BIGINT NOT NULL
        REFERENCES public.trips(id)
        ON DELETE CASCADE,

    event_type VARCHAR(50) NOT NULL,
    decision VARCHAR(100) NOT NULL,
    reason TEXT,
    event_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
